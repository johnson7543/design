"""Build an editable source study, not a completed Dotonbori product preset.

Run with Blender --background --python this-file --. The reviewed metric
source meshes are generated by prepare-dotonbori-source.py. Unknown bridge
elevations and facades are not reconstructed with guessed geometry.
"""

import argparse
from collections import Counter
import hashlib
import json
import math
from pathlib import Path
import re
import sys

import bmesh
import bpy
from mathutils import Vector


REPO = Path(__file__).resolve().parents[2]
ASSET_DIR = REPO / "assets/design-qr/dotonbori"
SCENE_NAME = "DesignQR Dotonbori Source Study"
OWNER = "designqr-dotonbori-study"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_palette():
    source = (REPO / "packages/designqr/src/designs/city/palette.ts").read_text(encoding="utf-8")
    palette = dict(re.findall(r"(\w+):\s*'(#[0-9a-fA-F]{6})'", source))
    return {key: palette[key] for key in ("eveningSky", "highRise", "gold", "bay", "navy", "coral", "ivory")}


def linear(hex_value):
    rgb = [int(hex_value[index:index + 2], 16) / 255 for index in (1, 3, 5)]
    return tuple(value / 12.92 if value <= .04045 else ((value + .055) / 1.055) ** 2.4 for value in rgb)


def make_material(role, swatch, roughness=.85):
    material = bpy.data.materials.new("dotonbori-" + role)
    material["designqr_owner"] = OWNER
    material["palette_role"] = role
    material["swatch"] = swatch
    material.diffuse_color = (*linear(swatch), 1)
    material.use_nodes = True
    shader = material.node_tree.nodes.get("Principled BSDF")
    shader.inputs["Base Color"].default_value = material.diffuse_color
    shader.inputs["Roughness"].default_value = roughness
    return material


def collection(scene, name):
    result = bpy.data.collections.new(name)
    result["designqr_owner"] = OWNER
    scene.collection.children.link(result)
    return result


def properties(obj, data):
    obj["designqr_owner"] = OWNER
    for key in ("id", "auditLabel", "evidence", "lod", "sourceFile", "sourceSha256", "sourceCreationDate", "materialInterpretation"):
        obj[key] = data[key]
    obj["survey_date_verified"] = False
    obj["source_units"] = "metres"
    obj["source_axes"] = "east, north, source elevation"
    obj["facade_detail_verified"] = False


def source_object(record, target, materials):
    mesh = bpy.data.meshes.new(record["id"] + "-source")
    mesh["designqr_owner"] = OWNER
    mesh.from_pydata(record["vertices"], [], record["triangles"])
    mesh.update()
    for material in materials:
        mesh.materials.append(material)
    for face, role in zip(mesh.polygons, record["triangleRoles"]):
        face.material_index = 2 if record["lod"] == 1 else 1 if role == "RoofSurface" else 0
    obj = bpy.data.objects.new(record["auditLabel"] + " source " + record["id"], mesh)
    target.objects.link(obj)
    properties(obj, record)
    obj["boundary_operation"] = "none; original source extent retained"
    return obj


def crop_object(original, target, extent):
    mesh = original.data.copy()
    mesh.name = original.data.name + "-crop"
    obj = original.copy()
    obj.data = mesh
    obj.name = original["auditLabel"] + " study " + original["id"]
    target.objects.link(obj)
    obj["boundary_operation"] = "clipped to draft tile; gold cut faces are authoring sections"
    bm = bmesh.new()
    bm.from_mesh(mesh)
    cut_faces = 0
    for point, normal in [((extent, 0, 0), (1, 0, 0)), ((-extent, 0, 0), (-1, 0, 0)),
                          ((0, extent, 0), (0, 1, 0)), ((0, -extent, 0), (0, -1, 0))]:
        result = bmesh.ops.bisect_plane(
            bm, geom=list(bm.verts) + list(bm.edges) + list(bm.faces),
            dist=1e-6, plane_co=point, plane_no=normal, clear_outer=True,
        )
        edges = [element for element in result["geom_cut"] if isinstance(element, bmesh.types.BMEdge) and element.is_boundary]
        if edges:
            filled = bmesh.ops.holes_fill(bm, edges=edges, sides=0)
            for face in filled["faces"]:
                face.material_index = 3
                cut_faces += 1
    # Bisect can generate two float32-identical intersections where a source
    # edge meets the crop. Weld only those boundary coordinates; retain the
    # untouched, full-extent source mesh in the originals collection.
    boundary_vertices = [v for v in bm.verts if any(abs(abs(v.co[axis]) - extent) < 1e-6 for axis in (0, 1))]
    before = len(bm.verts)
    bmesh.ops.remove_doubles(bm, verts=boundary_vertices, dist=1e-6)
    obj["crop_duplicate_vertices_removed"] = before - len(bm.verts)
    before_faces = len(bm.faces)
    bmesh.ops.dissolve_degenerate(bm, edges=list(bm.edges), dist=1e-6)
    obj["float32_degenerate_faces_removed"] = before_faces - len(bm.faces)
    bmesh.ops.triangulate(bm, faces=list(bm.faces))
    zero_area = [face for face in bm.faces if face.calc_area() <= 5e-9]
    obj["zero_area_export_triangles_removed"] = len(zero_area)
    bmesh.ops.delete(bm, geom=zero_area, context="FACES_ONLY")
    bmesh.ops.recalc_face_normals(bm, faces=list(bm.faces))
    bm.to_mesh(mesh)
    bm.free()
    mesh.update()
    obj["authoring_cut_faces"] = cut_faces
    return obj


def paths(geometry):
    kind, coordinates = geometry["type"], geometry.get("coordinates", [])
    if kind == "Polygon":
        return coordinates
    if kind == "MultiPolygon":
        return [ring for polygon in coordinates for ring in polygon]
    if kind == "LineString":
        return [coordinates]
    if kind == "MultiLineString":
        return coordinates
    if kind == "GeometryCollection":
        return [path for child in geometry["geometries"] for path in paths(child)]
    return []


def line_object(name, polylines, target, material, z=.035, width=.065):
    curve = bpy.data.curves.new(name, "CURVE")
    curve["designqr_owner"] = OWNER
    curve.dimensions = "3D"
    curve.resolution_u = 1
    curve.bevel_depth = width
    curve.bevel_resolution = 0
    for points in polylines:
        if len(points) < 2:
            continue
        spline = curve.splines.new("POLY")
        spline.points.add(len(points) - 1)
        for point, coordinate in zip(spline.points, points):
            point.co = (coordinate[0], coordinate[1], z, 1)
    curve.materials.append(material)
    obj = bpy.data.objects.new(name, curve)
    target.objects.link(obj)
    obj["designqr_owner"] = OWNER
    obj["evidence"] = "2D source-plan guide; display elevation is not measured terrain"
    return obj


def flat_polygon(name, points, target, material, z):
    mesh = bpy.data.meshes.new(name)
    mesh["designqr_owner"] = OWNER
    if points and points[0] == points[-1]:
        points = points[:-1]
    mesh.from_pydata([(p[0], p[1], z) for p in points], [], [list(range(len(points)))])
    mesh.materials.append(material)
    mesh.update()
    obj = bpy.data.objects.new(name, mesh)
    target.objects.link(obj)
    obj["designqr_owner"] = OWNER
    return obj


def water_rings(geometry):
    """Reject unsupported holes instead of painting them as water."""
    kind = geometry["type"]
    polygons = [geometry["coordinates"]] if kind == "Polygon" else geometry["coordinates"] if kind == "MultiPolygon" else []
    if not polygons:
        raise ValueError("Water guide must be polygonal")
    for rings in polygons:
        if len(rings) != 1:
            raise ValueError("Water guide holes need explicit triangulation")
        yield rings[0]


def camera(name, location, target, scene, cameras, scale, top=False):
    data = bpy.data.cameras.new(name)
    data["designqr_owner"] = OWNER
    data.type = "ORTHO"
    data.ortho_scale = scale
    data.clip_end = 1500
    obj = bpy.data.objects.new(name, data)
    cameras.objects.link(obj)
    obj.location = location
    obj.rotation_euler = (0, 0, 0) if top else (Vector(target) - obj.location).to_track_quat("-Z", "Y").to_euler()
    obj["designqr_owner"] = OWNER
    return obj


def fit_camera(obj, points, aspect):
    """Frame the actual study bounds without changing any site geometry."""
    orientation = obj.rotation_euler.to_quaternion()
    inverse = orientation.inverted()
    projected = [inverse @ (Vector(point) - obj.location) for point in points]
    xmin, xmax = min(p.x for p in projected), max(p.x for p in projected)
    ymin, ymax = min(p.y for p in projected), max(p.y for p in projected)
    obj.location += orientation @ Vector(((xmin + xmax) / 2, (ymin + ymax) / 2, 0))
    obj.data.ortho_scale = max(xmax - xmin, (ymax - ymin) * aspect) * 1.10


def validate_scene(scene, source, study_objects, review_points):
    """Record numerical preservation, topology and review framing."""
    differences, source_topology, study_topology = [], [], []
    original_objects = {obj["id"]: obj for obj in scene.objects if obj.get("boundary_operation", "").startswith("none;")}
    if set(original_objects) != {record["id"] for record in source["objects"]}:
        raise ValueError("Original Blender inventory differs from the source")
    for record in source["objects"]:
        obj = original_objects[record["id"]]
        if len(obj.data.vertices) != len(record["vertices"]) or len(obj.data.polygons) != len(record["triangles"]):
            raise ValueError("Original source topology count changed")
        differences.extend(abs(float(obj.data.vertices[i].co[axis]) - point[axis])
                           for i, point in enumerate(record["vertices"]) for axis in range(3))
    if max(differences) > 3e-5:
        raise ValueError("Source-coordinate difference exceeds float32 storage tolerance")
    for objects, report in [(original_objects.values(), source_topology), (study_objects, study_topology)]:
        for obj in objects:
            bm = bmesh.new()
            bm.from_mesh(obj.data)
            bad_edges = sum(not edge.is_manifold for edge in bm.edges)
            bm.free()
            if bad_edges:
                report.append({"sourceId": obj["id"], "nonManifoldEdges": bad_edges})
    if source_topology or study_topology:
        raise ValueError("Building topology requires review")
    framing = {}
    for obj in scene.objects:
        if obj.type != "CAMERA" or obj.name == "review-bridge-top":
            continue
        aspect = 1 if obj.name == "review-top" else 4 / 3
        inverse = obj.rotation_euler.to_quaternion().inverted()
        projected = [inverse @ (Vector(point) - obj.location) for point in review_points]
        maximum = max(max(abs(point.x) * 2 / obj.data.ortho_scale, abs(point.y) * 2 * aspect / obj.data.ortho_scale) for point in projected)
        if maximum > .95:
            raise ValueError("Review camera crops the study bounds: " + obj.name)
        framing[obj.name] = {"maximumNormalizedFrameCoordinate": maximum, "passed": True}
    with bpy.data.libraries.load(str(ASSET_DIR / "dotonbori-source.blend")) as (contents, selected):
        saved_scenes = list(contents.scenes)
    if saved_scenes != [SCENE_NAME]:
        raise ValueError("Saved master scene inventory differs")
    report = {
        "status": "pass", "claim": "source preservation and authoring integrity, not site accuracy",
        "sourceVertexMaxAbsoluteErrorM": max(differences), "sourceVertexCoordinateCount": len(differences),
        "sourceNonManifoldObjects": source_topology, "studyNonManifoldObjects": study_topology,
        "savedBlendScenes": saved_scenes, "cameraFraming": framing,
        "bridgeStudy": "Open dimensional surface by design; excluded from closed-building topology assertion",
    }
    (ASSET_DIR / "blender-validation.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")


def build():
    source_path = ASSET_DIR / "source-meshes.json"
    source = json.loads(source_path.read_text(encoding="utf-8"))
    if source["sourceAuditSha256"] != digest(REPO / "docs/designqr-package/cities/dotonbori/references/site-audit.json"):
        raise ValueError("Recompile the source meshes: the reviewed audit has changed")
    bridge_path = ASSET_DIR / "bridge-deck-study.json"
    bridge = json.loads(bridge_path.read_text(encoding="utf-8"))
    if bridge["sourceMeshSha256"] != digest(source_path):
        raise ValueError("Recompile the bridge registration: source meshes have changed")
    previous_scene = bpy.context.window.scene if bpy.context.window else None
    old = bpy.data.scenes.get(SCENE_NAME)
    if old:
        if old.get("designqr_owner") != OWNER:
            raise ValueError("Refusing to replace an unowned Blender scene")
        if any(obj.get("designqr_owner") != OWNER for obj in old.objects):
            raise ValueError("Preserve user-added objects before regenerating the owned study scene")
        if old == previous_scene:
            previous_scene = next((scene for scene in bpy.data.scenes if scene != old), None)
            if bpy.context.window and previous_scene:
                bpy.context.window.scene = previous_scene
        for obj in list(old.objects):
            if obj.get("designqr_owner") == OWNER:
                bpy.data.objects.remove(obj, do_unlink=True)
        bpy.data.scenes.remove(old)
        for data_type in (bpy.data.collections, bpy.data.meshes, bpy.data.curves, bpy.data.cameras, bpy.data.lights, bpy.data.materials, bpy.data.worlds):
            for block in list(data_type):
                if block.get("designqr_owner") == OWNER and block.users == 0:
                    data_type.remove(block)

    scene = bpy.data.scenes.new(SCENE_NAME)
    scene["designqr_owner"] = OWNER
    scene["status"] = "Source geometry study; bridge and facade reconstruction incomplete"
    scene["source_mesh_sha256"] = digest(source_path)
    scene["origin_longitude"] = source["originLongitudeLatitude"][0]
    scene["origin_latitude"] = source["originLongitudeLatitude"][1]
    scene["source_projection"] = source["horizontalProjection"]
    scene["vertical_operation"] = source["verticalOperation"]
    scene.unit_settings.system = "METRIC"
    scene.unit_settings.scale_length = 1
    originals = collection(scene, "01 Original source solids — complete extents")
    study = collection(scene, "02 Study solids — 160m crop")
    guides = collection(scene, "03 Map guides — elevations unresolved")
    review = collection(scene, "04 Review cameras and studio")
    bridge_study = collection(scene, "05 Bridge deck — incomplete dimensional study")

    swatches = read_palette()
    roles = {"source-wall": "ivory", "source-roof": "highRise", "lod1-unresolved": "coral",
             "authoring-cut": "gold", "map-line": "highRise", "water-plan": "bay", "reference-board": "navy",
             "bridge-dimension-study": "coral"}
    materials = {role: make_material(role, swatches[swatch]) for role, swatch in roles.items()}
    mesh_materials = [materials[role] for role in ("source-wall", "source-roof", "lod1-unresolved", "authoring-cut")]
    extent = source["cropSizeM"] / 2
    study_objects = []
    for record in source["objects"]:
        original = source_object(record, originals, mesh_materials)
        study_objects.append(crop_object(original, study, extent))
    originals.hide_render = True
    originals.hide_viewport = True

    bridge_mesh = bpy.data.meshes.new(bridge["id"])
    bridge_mesh["designqr_owner"] = OWNER
    bridge_mesh.from_pydata(bridge["vertices"], [], bridge["triangles"])
    bridge_mesh.materials.append(materials["bridge-dimension-study"])
    bridge_mesh.update()
    bridge_obj = bpy.data.objects.new(bridge["id"], bridge_mesh)
    bridge_study.objects.link(bridge_obj)
    bridge_obj["designqr_owner"] = OWNER
    for key in ("id", "status", "evidence", "verticalOperation", "surfaceOperation"):
        bridge_obj[key] = bridge[key]
    bridge_obj["source_drawing_sha256"] = bridge["drawing"]["sha256"]
    bridge_obj["source_mesh_sha256"] = digest(bridge_path)
    bridge_obj["finished_surface_verified"] = False
    bridge_obj["local_vertical_registration_verified"] = False

    for road in source["planReferences"]["roads"]:
        obj = line_object("road-plan " + road["sourceId"], paths(road["geometry"]), guides, materials["map-line"])
        obj["source_id"] = road["sourceId"]
        obj["source_z"] = road["minSourceZ"]
        obj["bridge_height_verified"] = False
    for index, record in enumerate(source["planReferences"]["mapFeatures"]):
        if record["layer"] == "WA":
            # A map patch on the reference board, not a reconstructed 3D canal.
            for part, ring in enumerate(water_rings(record["geometry"])):
                obj = flat_polygon(f"water-plan {index}-{part}", ring, guides, materials["water-plan"], .01)
                obj["evidence"] = "GSI mapped water area; planar study guide only"
                obj["water_elevation_verified"] = False
    board = flat_polygon("Reference board — not terrain", [(-extent, -extent), (extent, -extent), (extent, extent), (-extent, extent)], guides, materials["reference-board"], -.08)
    board["evidence"] = "authoring presentation; not surveyed ground"
    line_object("Draft crop boundary", [[(-extent,-extent),(extent,-extent),(extent,extent),(-extent,extent),(-extent,-extent)]], guides, materials["authoring-cut"], .06, .13)

    scene.render.engine = "BLENDER_EEVEE"
    scene.render.resolution_x = 1280
    scene.render.resolution_y = 960
    scene.render.resolution_percentage = 100
    scene.render.image_settings.file_format = "PNG"
    scene.render.film_transparent = False
    scene.view_settings.view_transform = "Standard"
    scene.world = bpy.data.worlds.new("Dotonbori review world")
    scene.world["designqr_owner"] = OWNER
    scene.world.use_nodes = True
    background = scene.world.node_tree.nodes.get("Background")
    background.inputs["Color"].default_value = (*linear(swatches["eveningSky"]), 1)
    background.inputs["Strength"].default_value = .6
    lamp_data = bpy.data.lights.new("Dotonbori review sun", "SUN")
    lamp_data["designqr_owner"] = OWNER
    lamp_data.energy = 2.2
    lamp_data.angle = math.radians(20)
    lamp = bpy.data.objects.new(lamp_data.name, lamp_data)
    lamp["designqr_owner"] = OWNER
    review.objects.link(lamp)
    lamp.rotation_euler = (math.radians(28), math.radians(-20), math.radians(-35))

    camera_specs = [
        ("review-axonometric", (175, 215, 190), (0, 0, 17), 215, False),
        ("review-top", (0, 0, 260), (0, 0, 0), 182, True),
        ("review-north", (0, 250, 28), (0, 0, 28), 180, False),
        ("review-south", (0, -250, 28), (0, 0, 28), 180, False),
        ("review-east", (250, 0, 28), (0, 0, 28), 180, False),
        ("review-west", (-250, 0, 28), (0, 0, 28), 180, False),
    ]
    cameras = {spec[0]: camera(*spec[:3], scene, review, spec[3], spec[4]) for spec in camera_specs}
    review_points = [tuple(vertex.co) for obj in study_objects for vertex in obj.data.vertices]
    review_points.extend([(-extent, -extent, -.08), (extent, -extent, -.08),
                          (extent, extent, -.08), (-extent, extent, -.08)])
    for name, obj in cameras.items():
        fit_camera(obj, review_points, 1 if name == "review-top" else 4 / 3)
    cx, cy = bridge["registration"]["centerEastNorthM"]
    camera("review-bridge-top", (cx, cy, 100), (cx, cy, 0), scene, review, 48, top=True)
    scene.camera = cameras["review-axonometric"]
    if bpy.context.window:
        bpy.context.window.scene = scene
    try:
        # Separate files prevent the unresolved bridge envelope from being
        # mistaken for source building geometry. Guides remain Blender-only.
        for file_name, objects in [("dotonbori-study.glb", study_objects),
                                   ("dotonbori-bridge-deck-study.glb", [bridge_obj])]:
            for obj in scene.objects:
                obj.select_set(False)
            for obj in objects:
                obj.select_set(True)
            with bpy.context.temp_override(scene=scene, view_layer=scene.view_layers[0]):
                bpy.ops.export_scene.gltf(filepath=str(ASSET_DIR / file_name), export_format="GLB",
                    use_selection=True, use_active_scene=True, export_cameras=False, export_lights=False,
                    export_materials="EXPORT", export_extras=True, export_texcoords=False, export_animations=False)
        bpy.data.libraries.write(str(ASSET_DIR / "dotonbori-source.blend"), {scene}, fake_user=True, compress=True)
    finally:
        if bpy.context.window and previous_scene:
            bpy.context.window.scene = previous_scene

    for obj in study_objects:
        obj.data.calc_loop_triangles()
    validate_scene(scene, source, study_objects, review_points)
    report = {
        "schema": "designqr-dotonbori-study", "version": 1,
        "status": scene["status"], "sourceMeshSha256": scene["source_mesh_sha256"],
        "sourceAuditSha256": source["sourceAuditSha256"], "blenderVersion": bpy.app.version_string,
        "units": "metres", "blenderAxes": ["east", "north", "source-height"],
        "gltfAxes": ["east", "source-height", "south"],
        "originLongitudeLatitude": source["originLongitudeLatitude"], "cropSizeM": source["cropSizeM"],
        "sourceBuildingCount": len(source["objects"]),
        "lodCounts": dict(Counter(record["lod"] for record in source["objects"])),
        "sourceTriangleCount": sum(len(record["triangles"]) for record in source["objects"]),
        "studyTriangleCount": sum(len(obj.data.loop_triangles) for obj in study_objects),
        "glbBytes": (ASSET_DIR / "dotonbori-study.glb").stat().st_size,
        "glbSha256": digest(ASSET_DIR / "dotonbori-study.glb"),
        "blendBytes": (ASSET_DIR / "dotonbori-source.blend").stat().st_size,
        "blendSha256": digest(ASSET_DIR / "dotonbori-source.blend"),
        "generatorSha256": digest(Path(__file__)),
        "blenderValidationSha256": digest(ASSET_DIR / "blender-validation.json"),
        "bridgeStudy": {
            "id": bridge["id"], "status": bridge["status"], "sourceSha256": digest(bridge_path),
            "generatorSha256": digest(REPO / "scripts/blender/prepare-dotonbori-bridge.py"),
            "glbBytes": (ASSET_DIR / "dotonbori-bridge-deck-study.glb").stat().st_size,
            "glbSha256": digest(ASSET_DIR / "dotonbori-bridge-deck-study.glb"),
            "triangles": len(bridge["triangles"]), "unresolved": bridge["unresolved"],
        },
        "materials": {material.name: {"role": role, "swatch": material["swatch"]} for role, material in materials.items()},
        "objects": [{"sourceId": obj["id"], "auditLabel": obj["auditLabel"], "lod": obj["lod"],
                     "cropDuplicateVerticesRemoved": obj["crop_duplicate_vertices_removed"],
                     "float32DegenerateFacesRemoved": obj["float32_degenerate_faces_removed"],
                     "zeroAreaExportTrianglesRemoved": obj["zero_area_export_triangles_removed"],
                     "authoringCutFaces": obj["authoring_cut_faces"], "studyObject": obj.name} for obj in study_objects],
        "unresolved": ["bridge surface reconciliation, ramps, stairs, rails and girders", "local bank elevations and connections", "registered facade detail and sign placement", "scene capture date"],
        "referenceGuides": "Plan guides and reference board have author-chosen display Z; they are not terrain and are excluded from GLB.",
        "attribution": "Derived from Osaka City PLATEAU source geometry and GSI optimized vector map references; processed by this repository.",
    }
    (ASSET_DIR / "study-manifest.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({key: report[key] for key in ("status", "sourceBuildingCount", "sourceTriangleCount", "studyTriangleCount", "glbBytes")}, indent=2))
    return scene


def render_reviews(scene, names):
    directory = ASSET_DIR / "reviews"
    directory.mkdir(exist_ok=True)
    previous_camera = scene.camera
    try:
        for name in names:
            scene.camera = scene.objects[name]
            scene.render.resolution_y = 1280 if name in ("review-top", "review-bridge-top") else 960
            scene.render.filepath = str(directory / (name + ".png"))
            bpy.ops.render.render(write_still=True, scene=scene.name)
    finally:
        scene.camera = previous_camera
        scene.render.resolution_y = 960


if __name__ == "__main__":
    args = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--render", action="store_true")
    options = parser.parse_args(args)
    study_scene = build()
    if options.render:
        render_reviews(study_scene, ["review-axonometric", "review-top", "review-north", "review-south", "review-east", "review-west", "review-bridge-top"])
