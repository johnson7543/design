"""Complete the display-level forecourt between the left shops and riverwalk.

Run with Shapely 2.1.2. Registered wall directions are recorded in the night
reference ledger. This fills an illustrative terrain gap, not a surveyed plaza.
"""
import hashlib
import json
from pathlib import Path
from shapely.geometry import Polygon, shape, mapping
from shapely.ops import unary_union
from shapely.affinity import translate

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'assets/design-qr/dotonbori'
refs = json.loads((ROOT / 'docs/designqr-package/cities/dotonbori/references/night-reference.json').read_text())
audit = json.loads((ROOT / 'docs/designqr-package/cities/dotonbori/references/east-site-audit.json').read_text())
waterfront = json.loads((ASSETS / 'waterfront-layout.json').read_text())
layout = json.loads((ASSETS / 'focus-layout.json').read_text())
water = unary_union([shape(g) for g in layout['plan']['water']])
walk = unary_union([shape(g) for g in waterfront['upperWalk'] + waterfront['lowerWalk']])
selected = {b['sourceId'] for b in layout['objects']}
buildings = unary_union([translate(shape(b['footprint']),
    xoff=layout['landmarkOffsetsEastNorthM'].get(b['sourceId'], [0, 0])[0],
    yoff=layout['landmarkOffsetsEastNorthM'].get(b['sourceId'], [0, 0])[1])
    for b in audit['buildings'] if b['sourceId'] in selected])
frame = Polygon(layout['outlineEastNorthM'])
parts = []
for front in refs['runtimeRegistration']['storefrontAccessRegistration']:
    if front['id'].endswith('west'):
        continue  # Dining windows only; no invented entrance or stair here.
    def point(x, depth):
        return [front['center'][i] + front['unitU'][i] * x + front['unitN'][i] * depth for i in range(2)]
    width = front['width']
    apron = Polygon([point(-width / 2, 0), point(width / 2, 0), point(width / 2, 8), point(-width / 2, 8)])
    apron = apron.intersection(frame).difference(water).difference(walk).difference(buildings)
    polygons = [apron] if apron.geom_type == 'Polygon' else list(apron.geoms)
    for polygon in polygons:
        if polygon.area < .1:
            continue
        assert polygon.intersection(water).area < 1e-7
        assert polygon.intersection(walk).area < 1e-7
        assert polygon.intersection(buildings).area < 1e-7
        # Verify the added patch actually touches the existing upper walk.
        assert polygon.distance(unary_union([shape(g) for g in waterfront['upperWalk']])) < 1e-6
        edges = []
        points = list(polygon.exterior.coords)
        for a, b in zip(points, points[1:]):
            mid = shape({'type': 'Point', 'coordinates': [(a[i] + b[i]) / 2 for i in range(2)]})
            # Avoid a second plinth skin against source building walls.
            if mid.distance(buildings) > .05:
                edges.append([a, b])
        parts.append({'front': front['id'], 'building': front['building'], 'polygon': mapping(polygon),
                      'height': front['base'], 'edges': edges, 'areaM2': polygon.area})
target = ROOT / 'packages/designqr/src/designs/city/dotonbori-storefront-access-data.ts'
header = '/** Generated by scripts/blender/prepare-dotonbori-storefront-access.py.\n * Source-clipped display forecourts; elevations and width are interpretations.\n */\n'
target.write_text(header + 'export const DOTONBORI_STOREFRONT_ACCESS = ' + json.dumps(parts, separators=(',', ':')) + ' as const;\n')
print(json.dumps({'patches': len(parts), 'areaM2': sum(p['areaM2'] for p in parts),
                  'generatorSha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}))
