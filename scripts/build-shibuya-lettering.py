def pack(recording,bounds):
 x0,y0,x1,y1=bounds; scale=1/(y1-y0)
 commands=[]
 for op,points in recording:
  code={'moveTo':0,'lineTo':1,'curveTo':2,'qCurveTo':3,'closePath':4,'endPath':4}[op]
  coords=[]
  for p in points:
   assert p is not None
   coords.extend([round((p[0]-x0)*scale,5),round((p[1]-y0)*scale,5)])
  commands.append([code,*coords])
 return {'width':round((x1-x0)*scale,5),'commands':commands}

def text_outline(style,text,tracking=0):
 font=fonts[style]; glyphs=font.getGlyphSet(); cmap=font.getBestCmap(); pen=RecordingPen(); bounds=BoundsPen(glyphs); x=0
 for ch in text:
  name=cmap[ord(ch)]; glyph=glyphs[name]; p=DecomposingRecordingPen(glyphs);glyph.draw(p)
  p.replay(TransformPen(pen,(1,0,0,1,x,0)));p.replay(TransformPen(bounds,(1,0,0,1,x,0)))
  x+=glyph.width+tracking
 return pack(pen.value,bounds.bounds)

