"""Portable sign lettering from the same pinned OFL font as Shibuya.

Source: https://github.com/notofonts/noto-cjk/blob/main/Sans/OTF/Japanese/NotoSansCJKjp-Medium.otf
Run: python3 scripts/build-dotonbori-lettering.py --sans /path/to/NotoSansCJKjp-Medium.otf
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen, RecordingPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
import argparse
import hashlib
import json

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--sans', required=True, type=Path)
args = parser.parse_args()
assert hashlib.sha256(args.sans.read_bytes()).hexdigest() == 'dd523e580e3413c480b2d701bf64e534c20f8419e3cfb6a44c2bdcd8d2a6c052', 'Unexpected source font'
font = TTFont(args.sans)
glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
labels = ['雪印メグミルク', '日商エステム', 'かぜに', '改源', 'CHINTAI', 'プロミス', 'SAMTY',
          'Asahi', 'SUPER DRY', 'AQUA', 'Haier', 'H&M', '牧場の朝', 'グ', 'リ', 'コ', 'えびす橋', 'たこ焼', 'お食事', '甘味', '珈琲', 'お品書', '入口', 'かに料理', 'かに道楽 本店',
          '明日を、元気に！', '大阪土産', '大阪 花ラング', 'FANCL', 'なにげない感動をずっと。', 'P!', 'ピップ', 'サロンパス',
          'ドン・キホーテ', 'えびすタワー', '驚安の殿堂', 'ド',
          '大阪', '川辺の夜', 'カラオケ', '道頓堀', '音楽', '夜の街', '空', '読書', '未来', '水辺', '夜景', '遊び',
          *[str(n) for n in range(1, 13)]]
out = {}
for label in labels:
    pen, bounds, x = RecordingPen(), BoundsPen(glyphs), 0
    for ch in label:
        glyph = glyphs[cmap[ord(ch)]]
        recording = DecomposingRecordingPen(glyphs)
        glyph.draw(recording)
        recording.replay(TransformPen(pen, (1, 0, 0, 1, x, 0)))
        recording.replay(TransformPen(bounds, (1, 0, 0, 1, x, 0)))
        x += glyph.width
    x0, y0, x1, y1 = bounds.bounds
    height = y1 - y0
    commands = []
    for op, points in pen.value:
        code = {'moveTo': 0, 'lineTo': 1, 'curveTo': 2, 'qCurveTo': 3, 'closePath': 4, 'endPath': 4}[op]
        commands.append([code, *[round(v, 5) for p in points for v in ((p[0] - x0) / height, (p[1] - y0) / height)]])
    out[label] = {'width': round((x1 - x0) / height, 5), 'commands': commands}
header = '''/** Generated by scripts/build-dotonbori-lettering.py. No runtime font fetch.
 * Noto Sans CJK JP: Copyright 2014–2021 Adobe, SIL OFL 1.1.
 * See packages/designqr/third-party-licenses/noto-cjk.txt.
 */
export const DOTONBORI_LETTERING: Readonly<Record<string, { width: number; commands: readonly (readonly number[])[] }>> = '''
path = Path(__file__).resolve().parents[1] / 'packages/designqr/src/designs/city/dotonbori-lettering-data.ts'
path.write_text(header + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f'{len(out)} labels, {sum(len(v["commands"]) for v in out.values())} path commands, {path.stat().st_size} bytes')
